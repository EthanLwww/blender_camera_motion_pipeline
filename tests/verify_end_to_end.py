def _resolve_blender() -> str:
    """The Blender *executable*, not the Python interpreter.

    Under ``blender -P`` ``sys.executable`` is Blender's bundled ``python.exe``,
    which cannot run ``-b -P``; ``bpy.app.binary_path`` is the right one.
    """
    override = os.environ.get("MP_BLENDER")
    if override:
        return override
    try:
        import bpy  # type: ignore

        if bpy.app.binary_path:
            return bpy.app.binary_path
    except Exception:
        pass
    return sys.executable


