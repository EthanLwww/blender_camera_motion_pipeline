def project_folder() -> str:
    """Newest ``blender_camera_*`` folder under ``GENERATED`` ("" when not there)."""
    if not os.path.isdir(GENERATED):
        return ""
    from blender_motion_pipeline.core.project import PROJECT_PREFIX

    found = sorted(
        os.path.join(GENERATED, name)
        for name in os.listdir(GENERATED)
        if name.startswith(PROJECT_PREFIX) and os.path.isdir(os.path.join(GENERATED, name))
    )
    return found[-1] if found else ""

STEPS: "list[tuple[str, bool, str]]" = []


def record(name: str, ok: bool, detail: str = "") -> None:
    STEPS.append((name, ok, detail))
    print(f"[{'ok  ' if ok else 'FAIL'}] {name}" + (f" -- {detail}" if detail else ""), flush=True)


def run_blender(script: str, args: "list[str]", *, blend: str = "", timeout: int = 1800):
    """Invoke Blender headlessly and return ``(exit_code, stdout, stderr)``."""
    command = [BLENDER, "-b"]
    if blend:
        command.append(blend)
    command += ["-P", script, "--"] + args
    print(f"  $ {' '.join(command[:4])} ... ({len(args)} arg(s))", flush=True)
    started = time.time()
    completed = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
    elapsed = time.time() - started
    print(f"    exit={completed.returncode} in {elapsed:.1f}s", flush=True)
    if completed.returncode != 0:
        tail = (completed.stdout or "")[-3000:]
        print("    --- stdout tail ---\n" + tail, flush=True)
        print("    --- stderr tail ---\n" + (completed.stderr or "")[-2000:], flush=True)
    return completed.returncode, completed.stdout or "", completed.stderr or ""


